import { describe, expect, it } from 'vitest';
import { pluralRu } from './plural';

// Фича 019 (FR-001; research R3): склонение числительного — одна функция домена.

describe('pluralRu', () => {
  const RECORD: [string, string, string] = ['запись', 'записи', 'записей'];

  it.each([
    [0, '0 записей'],
    [1, '1 запись'],
    [2, '2 записи'],
    [4, '4 записи'],
    [5, '5 записей'],
    [11, '11 записей'],
    [12, '12 записей'],
    [14, '14 записей'],
    [21, '21 запись'],
    [22, '22 записи'],
    [25, '25 записей'],
    [101, '101 запись'],
    [111, '111 записей'],
    [112, '112 записей'],
    [122, '122 записи'],
  ])('%i → «%s»', (n, expected) => {
    expect(pluralRu(n, RECORD)).toBe(expected);
  });

  it.each([
    [1, '1 период'],
    [3, '3 периода'],
    [5, '5 периодов'],
  ])('периоды: %i → «%s»', (n, expected) => {
    expect(pluralRu(n, ['период', 'периода', 'периодов'])).toBe(expected);
  });
});
